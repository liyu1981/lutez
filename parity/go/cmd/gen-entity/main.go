// Emits src/html/entity_tables.zig from upstream html.Entities (pinned submodule).
package main

import (
	"flag"
	"fmt"
	"os"
	"sort"
	"strings"

	"github.com/88250/lute/html"
)

func zigStr(s string) string {
	var b strings.Builder
	for i := 0; i < len(s); i++ {
		c := s[i]
		if c == '"' || c == '\\' {
			b.WriteByte('\\')
			b.WriteByte(c)
		} else if c >= 0x20 && c < 0x7f {
			b.WriteByte(c)
		} else {
			fmt.Fprintf(&b, "\\x%02x", c)
		}
	}
	return b.String()
}

func main() {
	out := flag.String("out", "../../src/html/entity_tables.zig", "output")
	flag.Parse()
	names := make([]string, 0, len(html.Entities))
	for k := range html.Entities {
		names = append(names, k)
	}
	sort.Strings(names)
	f, err := os.Create(*out)
	if err != nil {
		panic(err)
	}
	defer f.Close()
	fmt.Fprintln(f, "//! GENERATED by parity/go/cmd/gen-entity from upstream html/entity.go @ v1.7.8.")
	fmt.Fprintln(f, "//! Do not edit. Names are sorted for binary search; values are UTF-8 bytes.")
	fmt.Fprintln(f)
	fmt.Fprintln(f, "pub const Entity = struct { name: []const u8, value: []const u8 };")
	fmt.Fprintln(f)
	fmt.Fprintln(f, "pub const entities = [_]Entity{")
	for _, n := range names {
		v := html.Entities[n]
		fmt.Fprintf(f, "    .{ .name = \"%s\", .value = \"%s\" },\n", zigStr(n), zigStr(v))
	}
	fmt.Fprintln(f, "};")
	fmt.Printf("wrote %s: %d entities\n", *out, len(names))
}
