// Emits src/unicode/tables.zig from the Go/Unicode baseline used by the oracle.
package main

import (
	"flag"
	"fmt"
	"os"
	"unicode"

	"golang.org/x/text/cases"
)

const maxRune = 0x10FFFF

type rng struct{ lo, hi rune }

func ranges(pred func(rune) bool) []rng {
	var out []rng
	var start rune = -1
	for r := rune(0); r <= maxRune; r++ {
		ok := pred(r)
		if ok && start < 0 {
			start = r
		} else if !ok && start >= 0 {
			out = append(out, rng{start, r - 1})
			start = -1
		}
	}
	if start >= 0 {
		out = append(out, rng{start, maxRune})
	}
	return out
}

func writeRanges(b *os.File, name string, rs []rng) {
	fmt.Fprintf(b, "pub const %s = [_]Range{\n", name)
	for _, r := range rs {
		fmt.Fprintf(b, "    .{ .lo = 0x%X, .hi = 0x%X },\n", r.lo, r.hi)
	}
	fmt.Fprintf(b, "};\n\n")
}

func main() {
	out := flag.String("out", "../../src/unicode/tables.zig", "output")
	flag.Parse()
	f, err := os.Create(*out)
	if err != nil {
		panic(err)
	}
	defer f.Close()

	fmt.Fprintln(f, "//! GENERATED by parity/go/cmd/gen-unicode. Do not edit.")
	fmt.Fprintln(f, "//! Unicode data from the Go toolchain used for parity (see doc/UNICODE.md).")
	fmt.Fprintln(f)
	fmt.Fprintln(f, "pub const Range = struct { lo: u21, hi: u21 };")
	fmt.Fprintln(f)
	writeRanges(f, "space_ranges", ranges(func(r rune) bool { return unicode.IsSpace(r) || unicode.Is(unicode.Zs, r) }))
	writeRanges(f, "control_ranges", ranges(unicode.IsControl))
	writeRanges(f, "letter_ranges", ranges(unicode.IsLetter))
	writeRanges(f, "digit_ranges", ranges(unicode.IsDigit))
	writeRanges(f, "punct_ranges", ranges(unicode.IsPunct))
	writeRanges(f, "symbol_ranges", ranges(unicode.IsSymbol))
	writeRanges(f, "quotation_ranges", ranges(func(r rune) bool { return unicode.Is(unicode.Quotation_Mark, r) }))

	fmt.Fprintln(f, "pub const FoldPair = struct { r: u21, to: u21 };")
	fmt.Fprintln(f, "pub const simple_fold = [_]FoldPair{")
	for r := rune(0); r <= maxRune; r++ {
		if s := unicode.SimpleFold(r); s != r {
			fmt.Fprintf(f, "    .{ .r = 0x%X, .to = 0x%X },\n", r, s)
		}
	}
	fmt.Fprintln(f, "};")
	fmt.Fprintln(f)

	caser := cases.Fold()
	fmt.Fprintln(f, "pub const FoldEntry = struct { r: u21, off: u32, len: u8 };")
	var data []rune
	var entries []struct {
		r   rune
		off int
		len int
	}
	for r := rune(0); r <= maxRune; r++ {
		folded := []rune(caser.String(string(r)))
		if len(folded) == 1 && folded[0] == r {
			continue
		}
		entries = append(entries, struct {
			r   rune
			off int
			len int
		}{r, len(data), len(folded)})
		data = append(data, folded...)
	}
	fmt.Fprintln(f, "pub const fold_entries = [_]FoldEntry{")
	for _, e := range entries {
		fmt.Fprintf(f, "    .{ .r = 0x%X, .off = %d, .len = %d },\n", e.r, e.off, e.len)
	}
	fmt.Fprintln(f, "};")
	fmt.Fprintln(f)
	fmt.Fprintln(f, "pub const fold_data = [_]u21{")
	for _, r := range data {
		fmt.Fprintf(f, "    0x%X,\n", r)
	}
	fmt.Fprintln(f, "};")
	fmt.Printf("wrote %s: %d folds, %d runes\n", *out, len(entries), len(data))
}
