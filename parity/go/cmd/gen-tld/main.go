// gen-tld emits src/parse/tlds.zig from upstream parse/auto_link.go's allTLDs literal.
package main

import (
	"flag"
	"fmt"
	"os"
	"regexp"
	"sort"
	"strings"
)

func main() {
	out := flag.String("out", "../../src/parse/tlds.zig", "output")
	src := flag.String("src", "../../upstream/lute/parse/auto_link.go", "upstream source")
	flag.Parse()
	raw, err := os.ReadFile(*src)
	if err != nil {
		panic(err)
	}
	re := regexp.MustCompile("(?s)var allTLDs = `(.*?)`")
	m := re.FindSubmatch(raw)
	if m == nil {
		panic("allTLDs not found")
	}
	seen := map[string]bool{}
	var tlds []string
	for _, line := range strings.Split(string(m[1]), "\n") {
		s := strings.ToLower(strings.TrimSpace(line))
		if s == "" || strings.HasPrefix(s, "#") || seen[s] {
			continue
		}
		seen[s] = true
		tlds = append(tlds, s)
	}
	// The upstream GFM spec test calls AddAutoLinkDomainSuffix("baz"); mirror it so the
	// committed GFM corpus is reproducible without a mutable global.
	if !seen["baz"] {
		tlds = append(tlds, "baz")
	}
	sort.Strings(tlds)
	f, err := os.Create(*out)
	if err != nil {
		panic(err)
	}
	defer f.Close()
	fmt.Fprintln(f, "//! GENERATED by parity/go/cmd/gen-tld from upstream parse/auto_link.go @ v1.7.8.")
	fmt.Fprintln(f, "//! Public suffix allow-list used by GFM extended autolink domain validation.")
	fmt.Fprintln(f, "//! Includes \"baz\" to mirror upstream test/gfm_spec_test.go's AddAutoLinkDomainSuffix.")
	fmt.Fprintln(f)
	fmt.Fprintln(f, "pub const tlds = [_][]const u8{")
	for _, t := range tlds {
		fmt.Fprintf(f, "    %q,\n", t)
	}
	fmt.Fprintln(f, "};")
	fmt.Printf("wrote %s: %d TLDs\n", *out, len(tlds))
}
